// Builds supabase/seed.sql (reference data only) from data.js, the single source
// of truth for the org chart, buildings, roles, and sign-up domains.
import { buildings, emailDomains, organization, roleTemplates } from "../data.js";

export function sqlLiteral(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return String(value);
  if (Array.isArray(value)) return value.length ? `array[${value.map(sqlLiteral).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function insert(table, columns, rows, conflictKey) {
  const values = rows.map((row) => `  (${row.map(sqlLiteral).join(", ")})`).join(",\n");
  const updates = columns.filter((column) => column !== conflictKey).map((column) => `${column} = excluded.${column}`).join(", ");
  return `insert into ${table} (${columns.join(", ")}) values\n${values}\non conflict (${conflictKey}) do update set ${updates};\n`;
}

export function referenceSeedSql() {
  const parts = ["-- Generated by scripts/generate-seed.mjs from data.js. Do not edit by hand.\n"];

  parts.push(insert(
    "public.org_units",
    ["id", "name", "parent_id", "kind", "source", "sensitive"],
    organization.map((unit) => [unit.id, unit.name, unit.parentId, unit.kind, unit.source, Boolean(unit.sensitive)]),
    "id"
  ));

  parts.push(insert(
    "public.buildings",
    ["id", "map_no", "name", "type", "map_x", "map_y", "floors", "capacity", "layout", "hall_group", "gender", "owner_org_id", "offline", "capacity_note"],
    buildings.map((b) => [b.id, b.mapNo, b.name, b.type, b.x, b.y, b.floors ?? null, b.capacity ?? null, b.layout ?? null, b.hall ?? null, b.gender ?? null, b.orgId ?? null, Boolean(b.offline), b.capacityNote ?? null]),
    "id"
  ));

  parts.push(insert(
    "public.role_templates",
    ["key", "label", "level", "permissions", "default_scope_org_id", "scope_mode", "aggregate_only", "read_only", "building_scoped", "sensitive_grants", "can_invite", "max_access_days", "self_signup", "explanation"],
    Object.entries(roleTemplates).map(([key, role]) => [
      key, role.label, role.level, role.permissions, role.scopeOrgId ?? null, role.scopeMode,
      Boolean(role.aggregateOnly), Boolean(role.readOnly), Boolean(role.buildingScoped),
      role.sensitiveGrants ?? [], role.canInvite ?? [], role.maxAccessDays ?? null, Boolean(role.selfSignup), role.explanation
    ]),
    "key"
  ));

  parts.push(insert(
    "public.allowed_email_domains",
    ["domain", "kind", "default_role"],
    emailDomains.map((d) => [d.domain, d.kind, d.defaultRole]),
    "domain"
  ));

  return parts.join("\n");
}
